package cronjobs

import (
	"context"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"time"

	"gopanel/internal/model"
	"gopanel/internal/store"
	"gopanel/internal/sys"
	"gopanel/internal/validate"
)

var (
	ErrName     = errors.New("invalid cron job name")
	ErrDisabled = errors.New("cron job is disabled")
)

type Options struct {
	CronFile string
	LogDir   string
	Shell    string
}

type Input struct {
	Name     string `json:"name"`
	Schedule string `json:"schedule"`
	Command  string `json:"command"`
	Enabled  bool   `json:"enabled"`
}

type Reporter interface {
	Progress(pct int, message string)
	Logf(format string, args ...any)
}

type Service struct {
	st     *store.Store
	sys    sys.System
	logger *slog.Logger
	opts   Options
	mu     sync.Mutex
}

var nameRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9 _.-]{0,63}$`)

func New(st *store.Store, system sys.System, logger *slog.Logger, opts Options) *Service {
	if logger == nil {
		logger = slog.Default()
	}
	if opts.Shell == "" {
		opts.Shell = "/bin/bash"
	}
	return &Service{st: st, sys: system, logger: logger, opts: opts}
}

func (s *Service) List(ctx context.Context) ([]model.CronJob, error) {
	return s.st.ListCronJobs(ctx)
}

func (s *Service) Get(ctx context.Context, id int64) (*model.CronJob, error) {
	return s.st.GetCronJob(ctx, id)
}

func validateInput(in Input) error {
	if !nameRe.MatchString(strings.TrimSpace(in.Name)) {
		return ErrName
	}
	if err := validate.CronSchedule(in.Schedule); err != nil {
		return err
	}
	return validate.CronCommand(in.Command)
}

func (s *Service) Create(ctx context.Context, in Input, createdBy int64) (*model.CronJob, error) {
	in.Name = strings.TrimSpace(in.Name)
	in.Schedule = strings.TrimSpace(in.Schedule)
	if err := validateInput(in); err != nil {
		return nil, err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	job := &model.CronJob{
		Name:      in.Name,
		Schedule:  in.Schedule,
		Command:   in.Command,
		Enabled:   in.Enabled,
		CreatedBy: createdBy,
	}
	if err := s.st.CreateCronJob(ctx, job); err != nil {
		return nil, err
	}
	if err := s.syncLocked(ctx, 0); err != nil {
		_ = s.st.DeleteCronJob(ctx, job.ID)
		return nil, err
	}
	return job, nil
}

func (s *Service) Update(ctx context.Context, job *model.CronJob, in Input) (*model.CronJob, error) {
	in.Name = strings.TrimSpace(in.Name)
	in.Schedule = strings.TrimSpace(in.Schedule)
	if err := validateInput(in); err != nil {
		return nil, err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	prev := *job
	job.Name = in.Name
	job.Schedule = in.Schedule
	job.Command = in.Command
	job.Enabled = in.Enabled
	if err := s.st.UpdateCronJob(ctx, job); err != nil {
		*job = prev
		return nil, err
	}
	if err := s.syncLocked(ctx, 0); err != nil {
		*job = prev
		_ = s.st.UpdateCronJob(ctx, &prev)
		_ = s.syncLocked(ctx, 0)
		return nil, err
	}
	return job, nil
}

func (s *Service) Delete(ctx context.Context, id int64) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.syncLocked(ctx, id); err != nil {
		return err
	}
	return s.st.DeleteCronJob(ctx, id)
}

func (s *Service) SetEnabled(ctx context.Context, job *model.CronJob, enabled bool) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	prev := job.Enabled
	job.Enabled = enabled
	if err := s.st.UpdateCronJob(ctx, job); err != nil {
		job.Enabled = prev
		return err
	}
	if err := s.syncLocked(ctx, 0); err != nil {
		job.Enabled = prev
		_ = s.st.UpdateCronJob(ctx, job)
		_ = s.syncLocked(ctx, 0)
		return err
	}
	return nil
}

func (s *Service) Sync(ctx context.Context) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.syncLocked(ctx, 0)
}

func (s *Service) syncLocked(ctx context.Context, excludeID int64) error {
	jobs, err := s.st.ListCronJobs(ctx)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Managed by GoPanel. Do not edit this file manually.\n")
	b.WriteString("SHELL=" + s.opts.Shell + "\n")
	b.WriteString("PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n")
	for _, job := range jobs {
		if job.ID == excludeID || !job.Enabled {
			continue
		}
		if validate.CronSchedule(job.Schedule) != nil || validate.CronCommand(job.Command) != nil {
			s.logger.Warn("skipping invalid cron job", "id", job.ID)
			continue
		}
		label := strings.Map(func(r rune) rune {
			if r == '\n' || r == '\r' || r == 0 {
				return -1
			}
			return r
		}, job.Name)
		fmt.Fprintf(&b, "# gopanel:%d %s\n", job.ID, label)
		fmt.Fprintf(&b, "%s root %s\n", job.Schedule, escapeCommand(job.Command))
	}
	if err := writeFile(s.opts.CronFile, []byte(b.String())); err != nil {
		return fmt.Errorf("write cron file: %w", err)
	}
	return nil
}

func escapeCommand(command string) string {
	command = strings.ReplaceAll(command, "%", `\%`)
	return command
}

func writeFile(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".gopanel-cron-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}

func (s *Service) RunNow(ctx context.Context, job *model.CronJob, report Reporter) error {
	if !job.Enabled {
		return ErrDisabled
	}
	if err := validate.CronCommand(job.Command); err != nil {
		return err
	}
	if report == nil {
		report = nopReporter{}
	}
	logFile, err := s.openLog(job.ID)
	if err != nil {
		s.logger.Warn("open cron log", "id", job.ID, "error", err)
	}
	if logFile != nil {
		defer logFile.Close()
	}
	header := fmt.Sprintf("=== %s run-now: %s ===\n", time.Now().Format(time.RFC3339), job.Command)
	if logFile != nil {
		logFile.WriteString(header)
	}
	report.Logf("%s", strings.TrimSpace(header))
	report.Progress(5, "Starting command")
	sink := func(chunk string) {
		if logFile != nil {
			logFile.WriteString(chunk)
		}
		report.Logf("%s", chunk)
	}
	runCtx, cancel := context.WithTimeout(ctx, 30*time.Minute)
	defer cancel()
	res, runErr := s.sys.Stream(runCtx, s.opts.Shell, []string{"-c", job.Command}, sys.ExecOpts{Timeout: 30 * time.Minute, MaxOutput: 4 << 20}, sink)
	status := "success"
	if runErr != nil {
		status = "failed"
		report.Logf("Command failed: %v", runErr)
	}
	if logFile != nil {
		fmt.Fprintf(logFile, "\n=== exit=%d status=%s ===\n", res.ExitCode, status)
	}
	report.Progress(100, status)
	if err := s.st.SetCronRun(context.WithoutCancel(ctx), job.ID, time.Now().Unix(), status); err != nil {
		s.logger.Warn("record cron run", "id", job.ID, "error", err)
	}
	return runErr
}

func (s *Service) openLog(id int64) (*os.File, error) {
	dir := filepath.Join(s.opts.LogDir, "cron")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, err
	}
	path := filepath.Join(dir, fmt.Sprintf("cron-%d.log", id))
	if info, err := os.Stat(path); err == nil && info.Size() > 2<<20 {
		if err := os.Truncate(path, 0); err != nil {
			return nil, err
		}
	}
	return os.OpenFile(path, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o640)
}

func (s *Service) Log(ctx context.Context, id int64, lines int) (string, error) {
	if _, err := s.st.GetCronJob(ctx, id); err != nil {
		return "", err
	}
	if lines <= 0 {
		lines = 200
	}
	if lines > 2000 {
		lines = 2000
	}
	path := filepath.Join(s.opts.LogDir, "cron", fmt.Sprintf("cron-%d.log", id))
	f, err := os.Open(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return "", nil
		}
		return "", err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return "", err
	}
	const tailBytes = 128 << 10
	offset := int64(0)
	if info.Size() > tailBytes {
		offset = info.Size() - tailBytes
	}
	buf := make([]byte, info.Size()-offset)
	if _, err := f.ReadAt(buf, offset); err != nil && !errors.Is(err, io.EOF) {
		return "", err
	}
	text := strings.Split(strings.TrimRight(string(buf), "\n"), "\n")
	if len(text) > lines {
		text = text[len(text)-lines:]
	}
	return strings.Join(text, "\n"), nil
}

type nopReporter struct{}

func (nopReporter) Progress(int, string) {}
func (nopReporter) Logf(string, ...any)  {}
